import type { Category, PromptGame } from "./catalog.ts";
export interface Prompt {
  id: string;
  text: string;
  category: Exclude<Category, "all">;
}
const build = (
  prefix: string,
  category: Prompt["category"],
  texts: string[],
): Prompt[] =>
  texts.map((text, index) => ({
    id: `${prefix}-${category}-${index}`,
    text,
    category,
  }));

